/**
 * Standard Brand Icon conforming to Simple Icons format.
 *
 * @param {string} name - Brand name (e.g. "github", "google", "docker", "react", "python", "aws")
 * @param {number|string} size - Pixel size (default: 20)
 * @param {boolean} colored - Whether to render with official brand color (default: true)
 * @param {string} className - Additional CSS classes
 */
export default function BrandIcon({
  name,
  size = 20,
  colored = true,
  className = "",
  style = {},
  ...props
}) {
  if (!name) return null;

  const key = String(name).toLowerCase().replace(/[-_ .]/g, "");
  const brand = BRAND_DATA[key];

  if (!brand) {
    return (
      <span
        className={`inline-flex items-center justify-center font-bold text-xs uppercase px-1.5 py-0.5 rounded bg-base-200 border border-base-300 ${className}`}
        style={{ minWidth: size, height: size, ...style }}
        {...props}
      >
        {name.slice(0, 3)}
      </span>
    );
  }

  const fillColor = colored ? brand.color : "currentColor";

  return (
    <svg
      role="img"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill={fillColor}
      className={`shrink-0 transition-colors ${className}`}
      style={style}
      xmlns="http://www.w3.org/2000/svg"
      aria-label={brand.title}
      {...props}
    >
      <title>{brand.title}</title>
      <path d={brand.path} />
    </svg>
  );
}

